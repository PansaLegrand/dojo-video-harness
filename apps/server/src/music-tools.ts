import { z } from "zod/v3";
import type { AgentTool } from "../../../packages/agent/src/tools";
import type { NativeAgentRequest } from "../../../packages/core/src/lib/video-project/agent-runtime";
import type { MusicService } from "./music-service";
const parameters = z
  .object({
    prompt: z.string().trim().min(1).max(1000),
    title: z.string().trim().min(1).max(80),
    trackId: z.string().min(1).max(191),
    fromFrame: z.number().int().nonnegative(),
    durationInFrames: z.number().int().positive(),
    volume: z.number().min(0).max(1).default(0.2),
    continueEditing: z.boolean().default(false),
  })
  .strict();
export function musicTools(
  service: MusicService,
  projectId: string,
  runId: string,
  request: NativeAgentRequest,
): AgentTool[] {
  return [
    {
      name: "prepare_background_music",
      effect: "ask",
      description:
        "Prepare an instrumental background music job for user approval. Inspect tracks first. Whole-project scope required. The Music card explicitly approves provider spending and automatic insertion up to the requested duration. No music is generated by this tool itself. For a request that also needs visual edits, set continueEditing:true, then continue to propose_edit; otherwise this tool ends the turn. Music placement must fit the existing project duration.",
      parameters: {
        type: "object",
        properties: {
          prompt: {
            type: "string",
            description: "Mood, instruments and genre; no lyrics.",
          },
          title: { type: "string" },
          trackId: { type: "string" },
          fromFrame: { type: "integer", minimum: 0 },
          durationInFrames: { type: "integer", minimum: 1 },
          volume: { type: "number", minimum: 0, maximum: 1 },
          continueEditing: {
            type: "boolean",
            description:
              "Keep the tool loop running so the same instruction can also produce a visual edit proposal.",
          },
        },
        required: [
          "prompt",
          "title",
          "trackId",
          "fromFrame",
          "durationInFrames",
        ],
        additionalProperties: false,
      },
      execute: async (raw, signal) => {
        signal.throwIfAborted();
        if (request.authoring?.scope?.kind !== "project")
          throw new Error(
            "Background music currently requires Whole project edit scope. Ask the user to choose that scope before preparing music.",
          );
        const { continueEditing, ...input } = parameters.parse(raw);
        const job = await service.propose(projectId, {
          ...input,
          sourceRunId: runId,
          operationId: `music:${runId}`,
          baseRevision: request.baseRevision,
          baseHash: request.baseHash,
        });
        if (signal.aborted) {
          await service.cancel(projectId, job.id);
          signal.throwIfAborted();
        }
        if (continueEditing)
          return {
            kind: "observation",
            value: {
              musicJobId: job.id,
              status: job.status,
              message:
                "Music plan is ready for explicit approval. Continue the requested visual edits with propose_edit. Do not claim music is generated or inserted yet.",
            },
          };
        return {
          kind: "terminal",
          result: {
            contract: "video-project-commands",
            version: 1,
            baseRevision: request.baseRevision,
            baseHash: request.baseHash,
            outcome: "answer",
            proposal: null,
            summary: `Music plan ready: ${input.title}. Review the Background music card and approve generation and automatic timeline insertion.`,
          },
        };
      },
    },
  ];
}
