export type ToolEffect = "read" | "propose" | "ask";
export type ToolSpec = {
  name: string;
  description: string;
  parameters: Record<string, unknown>;
};
export type AgentTool<T> = ToolSpec & {
  effect: ToolEffect;
  execute(
    args: unknown,
    signal: AbortSignal,
  ): Promise<
    | { kind: "observation"; value: unknown; pinned?: boolean }
    | { kind: "terminal"; result: T }
  >;
};
