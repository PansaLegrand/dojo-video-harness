export function motionCopy(locale: string): typeof en {
  const values = translations[locale];
  return values
    ? (Object.fromEntries(
        Object.keys(en).map((key, index) => [key, values[index]]),
      ) as typeof en)
    : en;
}
export function motionTemplateName(id: string, locale: string) {
  const c = motionCopy(locale);
  return id === "product-launch"
    ? c.product
    : id === "editorial-collage"
      ? c.collage
      : c.geometric;
}
